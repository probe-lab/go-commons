// banner renders name in the ANSI Shadow font with a line under it that
// names ProbeLab and the year. A name with a character the font lacks is
// printed as is.
func banner(name string, year int) string {
	var lines []string
	for _, r := range strings.ToUpper(name) {
		glyph, ok := bannerFont[r]
		if !ok {
			lines = []string{name}
			break
		}

		if lines == nil {
			lines = make([]string, len(glyph))
		}

		for i, row := range glyph {
			lines[i] += row
		}
	}

	// All rows of a glyph have the same width, so all lines do too.
	width := 0
	if len(lines) > 0 {
		width = utf8.RuneCountInString(lines[0])
	}

	sub := fmt.Sprintf("powered by ProbeLab · %d", year)
	pad := max(0, width-utf8.RuneCountInString(sub))

	var b strings.Builder
	for _, line := range lines {
		b.WriteString(strings.TrimRight(line, " "))
		b.WriteByte('\n')
	}
	b.WriteString(strings.Repeat(" ", pad) + sub + "\n\n")

	return b.String()
}

